-- Schema for the "Serie pomiarowe" API (zai-api-26z.yaml).
-- Executed by the postgres image on first start (empty data volume) from /docker-entrypoint-initdb.d.
-- Column names follow the JPA entities in backend/ (Hibernate snake_case naming).

-- Administrator accounts (/api/auth/login, /api/auth/password).
CREATE TABLE admin_users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL          -- BCrypt
);

-- Issued bearer tokens; only the SHA-256 of the token is stored. Logout deletes the row.
CREATE TABLE auth_tokens (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash VARCHAR(64)              NOT NULL UNIQUE,
    admin_id   BIGINT                   NOT NULL REFERENCES admin_users (id) ON DELETE CASCADE,
    expires_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

-- Schema: Series / SeriesInput.
CREATE TABLE series (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name      VARCHAR(100)     NOT NULL CHECK (char_length(name) >= 1),
    min_value DOUBLE PRECISION NOT NULL,
    max_value DOUBLE PRECISION NOT NULL,
    color     VARCHAR(7)       NOT NULL CHECK (color ~ '^#[0-9A-Fa-f]{6}$'),
    icon      VARCHAR(255),
    unit      VARCHAR(20),
    CONSTRAINT series_range_check CHECK (min_value < max_value)
);

-- Schema: Sensor / SensorCreated. Sensors are removed together with their series.
CREATE TABLE sensors (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                VARCHAR(100)                NOT NULL CHECK (char_length(name) >= 1),
    series_id           BIGINT                      NOT NULL REFERENCES series (id) ON DELETE CASCADE,
    api_key_hash        VARCHAR(64)                 NOT NULL UNIQUE,   -- SHA-256 of the API key
    created_at          TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    last_measurement_at TIMESTAMP(6) WITH TIME ZONE
);

CREATE INDEX sensors_series_id_idx ON sensors (series_id);

-- Schema: Measurement. Removed together with their series; sensor_id is deliberately not a
-- foreign key because measurements outlive the sensor that sent them.
CREATE TABLE measurements (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    series_id      BIGINT                      NOT NULL REFERENCES series (id) ON DELETE CASCADE,
    sensor_id      BIGINT,
    measured_value DOUBLE PRECISION            NOT NULL,
    measured_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

-- GET /api/measurements?series=...&from=...&to=... filters by series and time, sorted by time.
CREATE INDEX measurements_series_id_measured_at_idx ON measurements (series_id, measured_at);
CREATE INDEX measurements_measured_at_idx ON measurements (measured_at);
